import React, { useState, useEffect } from 'react';
import TopMonographBar from './components/TopMonographBar';
import FilingCabinet from './components/FilingCabinet';
import WorkingDossier from './components/WorkingDossier';
import EvidenceInspector from './components/EvidenceInspector';
import InteractiveAgentPipeline from './components/InteractiveAgentPipeline';
import ScreeningModal from './components/ScreeningModal';
import { BookOpen, FileSearch, Library } from 'lucide-react';

export default function App() {
  const [viewMode, setViewMode] = useState('pipeline'); // 'pipeline' | 'desk'
  const [deskSection, setDeskSection] = useState('library');
  const [requestedDossierTab, setRequestedDossierTab] = useState('synthesis');
  const [papers, setPapers] = useState([]);
  const [selectedPaper, setSelectedPaper] = useState(null);
  const [paradigmFilter, setParadigmFilter] = useState('all');
  const [searchQuery, setSearchQuery] = useState('');
  
  const [report, setReport] = useState({ content: '', diagrams: {} });
  const [comparative, setComparative] = useState({});
  const [status, setStatus] = useState({ status: 'ready', counts: {} });
  
  const [activeProvenance, setActiveProvenance] = useState(null);
  const [activeDiagramKey, setActiveDiagramKey] = useState('themes_mindmap');
  const [screeningModalOpen, setScreeningModalOpen] = useState(false);

  const [fieldLogs, setFieldLogs] = useState([
    "[READY] Multi-Agent Literature Review Environment Initialized.",
    "[READY] NVIDIA NIM Provider Active (meta/muse-glimmer-30b).",
    "[STEP 1] Awaiting research topic query from user to trigger Relevance Screening Agent..."
  ]);

  // Fetch initial corpus, status, report & comparative matrix
  const loadData = async () => {
    try {
      const [resStatus, resCorpus, resReport, resComp] = await Promise.all([
        fetch('/api/status').then(r => r.json()).catch(() => ({})),
        fetch('/api/corpus').then(r => r.json()).catch(() => ({ papers: [] })),
        fetch('/api/report').then(r => r.json()).catch(() => ({ content: '', diagrams: {} })),
        fetch('/api/comparative').then(r => r.json()).catch(() => ({}))
      ]);

      setStatus(resStatus);
      const fetchedPapers = resCorpus.papers || [];
      setPapers(fetchedPapers);
      if (fetchedPapers.length > 0 && !selectedPaper) {
        setSelectedPaper(fetchedPapers[0]);
      }
      setReport(resReport);
      setComparative(resComp);
    } catch (err) {
      console.error('Error loading digital binder data:', err);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  const handleCitationClick = (citation) => {
    setActiveProvenance(citation);
    setFieldLogs(prev => [
      `[${new Date().toLocaleTimeString()}] Provenance: Inspected claim [${citation.label}] and jumping to Page ${citation.page || 1}...`,
      ...prev.slice(0, 20)
    ]);
  };

  const handleViewDiagram = (diagramKey) => {
    setActiveDiagramKey(diagramKey);
  };

  const handleResetCorpus = async () => {
    try {
      await fetch('/api/clear-corpus', { method: 'POST' });
      await loadData();
      setViewMode('pipeline');
      setFieldLogs(prev => [
        `[${new Date().toLocaleTimeString()}] Working memory and corpus cleared. Ready for fresh research topic!`,
        ...prev.slice(0, 20)
      ]);
    } catch (err) {
      console.error('Reset error:', err);
    }
  };

  const handleExport = (format) => {
    if (format === 'markdown') {
      const blob = new Blob([report.content || "# Literature Review Synthesis\n\nGenerated by NLP-05"], { type: 'text/markdown' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'literature_review_report.md';
      a.click();
    } else if (format === 'latex') {
      const latexContent = `\\documentclass{article}
\\usepackage{amsmath,amssymb,graphicx}
\\title{Automated Literature Review: Synthesis of Multi-Agent Collaboration}
\\author{NLP-05 Agentic AI Research Group \\\\ RV College of Engineering}
\\date{\\today}
\\begin{document}
\\maketitle
\\begin{abstract}
Synthesizes arXiv preprints spanning reasoning-action synergy, tool use, and multi-agent software engineering.
\\end{abstract}
\\end{document}`;
      const blob = new Blob([latexContent], { type: 'text/x-tex' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = 'literature_review.tex';
      a.click();
    } else if (format === 'print') {
      window.print();
    }
  };

  return (
    <div className="h-screen w-screen flex flex-col dot-matrix-bg overflow-hidden select-text font-sans bg-[#F9F8F6] m-0 p-0">
      
      {/* Top Monograph & Navigation Bar */}
      <TopMonographBar
        status={status}
        viewMode={viewMode}
        setViewMode={setViewMode}
        paradigmFilter={paradigmFilter}
        setParadigmFilter={setParadigmFilter}
        onOpenScreening={() => setScreeningModalOpen(true)}
        onResetCorpus={handleResetCorpus}
        onExport={handleExport}
        totalPapers={papers.length}
      />

      {/* Main View: Pipeline Stepper OR Full 3-Pane Scholar's Desk */}
      {viewMode === 'pipeline' ? (
        <InteractiveAgentPipeline
          papers={papers}
          onRefreshCorpus={loadData}
          onSwitchToDeskView={() => setViewMode('desk')}
          fieldLogs={fieldLogs}
          setFieldLogs={setFieldLogs}
        />
      ) : (
        <div className="flex-1 flex flex-col overflow-hidden w-full bg-stone-50/70">
          <nav className="shrink-0 border-b border-stone-200 bg-white px-6 py-3" aria-label="Binder desk sections">
            <div className="max-w-6xl mx-auto flex items-center justify-between gap-5">
              <div>
                <h2 className="font-serif text-base font-bold text-stone-900">Binder's Desk</h2>
                <p className="text-[11px] text-stone-500 mt-0.5">Choose one workspace at a time to keep your research focused.</p>
              </div>
              <div className="grid grid-cols-3 gap-1.5 rounded-xl bg-stone-100 border border-stone-200 p-1.5" role="tablist">
                {[
                  { id: 'library', label: 'Paper Library', hint: `${papers.length} papers`, icon: Library },
                  { id: 'review', label: 'Review Workspace', hint: 'Synthesis and analysis', icon: BookOpen },
                  { id: 'evidence', label: 'Evidence Lab', hint: 'PDFs, maps and logs', icon: FileSearch },
                ].map(({ id, label, hint, icon: Icon }) => (
                  <button
                    key={id}
                    type="button"
                    role="tab"
                    aria-selected={deskSection === id}
                    onClick={() => setDeskSection(id)}
                    className={`min-w-40 rounded-lg px-4 py-2 text-left transition-all flex items-center gap-2.5 ${
                      deskSection === id
                        ? 'bg-white text-stone-900 shadow-sm ring-1 ring-stone-200'
                        : 'text-stone-500 hover:text-stone-800 hover:bg-white/60'
                    }`}
                  >
                    <Icon className={`w-4 h-4 shrink-0 ${deskSection === id ? 'text-amber-700' : 'text-stone-400'}`} />
                    <span>
                      <span className="block text-xs font-semibold">{label}</span>
                      <span className="block text-[10px] mt-0.5 font-normal">{hint}</span>
                    </span>
                  </button>
                ))}
              </div>
            </div>
          </nav>

          <div className="flex-1 overflow-hidden" role="tabpanel">
            {deskSection === 'library' && (
              <FilingCabinet
                workspace
                papers={papers}
                selectedPaper={selectedPaper}
                onSelectPaper={(paper) => {
                  setSelectedPaper(paper);
                  setRequestedDossierTab('paper');
                  setDeskSection('review');
                }}
                searchQuery={searchQuery}
                setSearchQuery={setSearchQuery}
                paradigmFilter={paradigmFilter}
              />
            )}

            {deskSection === 'review' && (
              <WorkingDossier
                report={report}
                comparative={comparative}
                selectedPaper={selectedPaper}
                requestedTab={requestedDossierTab}
                onTabChange={setRequestedDossierTab}
                onCitationClick={(citation) => {
                  handleCitationClick(citation);
                  setDeskSection('evidence');
                }}
                onViewDiagram={(diagramKey) => {
                  handleViewDiagram(diagramKey);
                  setDeskSection('evidence');
                }}
              />
            )}

            {deskSection === 'evidence' && (
              <EvidenceInspector
                workspace
                activeProvenance={activeProvenance}
                diagrams={report.diagrams || {}}
                activeDiagramKey={activeDiagramKey}
                setActiveDiagramKey={setActiveDiagramKey}
                selectedPaper={selectedPaper}
                fieldLogs={fieldLogs}
              />
            )}
          </div>
        </div>
      )}

      {/* Quick Screening Modal */}
      <ScreeningModal
        isOpen={screeningModalOpen}
        onClose={() => setScreeningModalOpen(false)}
        onRefreshCorpus={loadData}
      />

    </div>
  );
}
